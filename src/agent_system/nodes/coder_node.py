"""Coder node — Main LLM in CODING mode. Only runs after Gate 1."""

from __future__ import annotations

import logging
import os
import sys
import uuid
from pathlib import Path
from typing import Any, Dict, List

logger = logging.getLogger(__name__)

_SRC = Path(__file__).resolve().parents[2]
if str(_SRC) not in sys.path:
    sys.path.insert(0, str(_SRC))


def coder_node(state: Dict[str, Any]) -> Dict[str, Any]:
    """Generate and apply patches only when Gate 1 is valid."""
    from adapters.llm_adapter import LLMAdapter, LLMMode
    from agent_system.security.tool_executor import make_executor_from_state, PermissionError

    if not state.get("gate1_approved"):
        return {
            "status": "failed",
            "error": "Coder blocked: Gate 1 not approved",
            "events": [{"type": "coder_blocked", "reason": "gate1_not_approved"}],
        }

    workspace = os.getenv("WORKSPACE_ROOT", "workspace")
    Path(workspace).mkdir(parents=True, exist_ok=True)

    executor = make_executor_from_state(state, workspace)

    user_request = state.get("user_request", "")
    plan = state.get("plan", "")
    scope = state.get("scope_paths") or ["workspace/"]

    system = (
        "You are the Coder for Agent System v0.5 operating in CODING mode. "
        "Produce a minimal, correct code change for the approved plan. "
        "Output a single file path and its full new content in this format:\n"
        "FILE: <relative/path.py>\n"
        "```\n<code>\n```\n"
        "Only touch paths inside the approved scope."
    )

    from adapters.llm_adapter import ModelProvider
    prov_name = os.getenv("LLM_PROVIDER", "gemini").lower()
    try:
        prov = ModelProvider(prov_name)
    except ValueError:
        prov = ModelProvider.GEMINI
    adapter = LLMAdapter(
        default_provider=prov,
        mock=os.getenv("LLM_MOCK", "1").lower() in ("1", "true", "yes"),
    )

    try:
        resp = adapter.complete(
            messages=[
                {"role": "system", "content": system},
                {
                    "role": "user",
                    "content": f"Plan:\n{plan}\n\nUser request:\n{user_request}\n\nScope: {scope}",
                },
            ],
            mode=LLMMode.CODING,
        )
        content = resp.content or ""
        model_used = resp.model
        # Refuse simulated tool_calls from MOCK that claim write success without executor
        if resp.tool_calls and adapter.mock:
            logger.info("Ignoring mock tool_calls — must go through ToolExecutor")
    except Exception as exc:
        logger.warning("Coder LLM failed: %s", exc)
        content = (
            "FILE: workspace/hello_agent.py\n"
            "```\n"
            '"""Generated by Agent System v0.5 Coder (fallback)."""\n'
            f'print("Hello from agent — request: {user_request[:80]}")\n'
            "```\n"
        )
        model_used = "fallback"

    # Parse FILE blocks and write via executor
    files_changed: List[str] = []
    patches: List[Dict[str, Any]] = []
    action_id = str(uuid.uuid4())

    lines = content.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        if line.upper().startswith("FILE:"):
            rel_path = line.split(":", 1)[1].strip()
            # collect fenced code
            i += 1
            body_lines = []
            in_fence = False
            while i < len(lines):
                l = lines[i]
                if l.strip().startswith("```"):
                    if not in_fence:
                        in_fence = True
                        i += 1
                        continue
                    else:
                        break
                if in_fence:
                    body_lines.append(l)
                i += 1
            body = "\n".join(body_lines) + "\n"
            try:
                result = executor.execute_write(
                    tool_name="write_file",
                    path=rel_path,
                    content=body,
                    action_id=f"{action_id}:{rel_path}",
                )
                files_changed.append(rel_path)
                patches.append({"path": rel_path, "result": result})
            except PermissionError as pe:
                logger.error("Permission denied writing %s: %s", rel_path, pe)
                return {
                    "status": "failed",
                    "error": str(pe),
                    "code_patches": patches,
                    "files_changed": files_changed,
                    "events": [
                        {
                            "type": "coder_permission_denied",
                            "path": rel_path,
                            "error": str(pe),
                        }
                    ],
                }
        i += 1

    if not files_changed:
        # Guarantee at least one write in mock for demo
        rel = "workspace/agent_output.py"
        body = (
            '"""Auto-generated by Agent System v0.5"""\n'
            f'REQUEST = """{user_request[:200]}"""\n'
            "print(REQUEST)\n"
        )
        try:
            result = executor.execute_write(
                "write_file", rel, body, action_id=f"{action_id}:fallback"
            )
            files_changed.append(rel)
            patches.append({"path": rel, "result": result})
        except PermissionError as pe:
            return {
                "status": "failed",
                "error": str(pe),
                "events": [{"type": "coder_permission_denied", "error": str(pe)}],
            }

    return {
        "code_patches": patches,
        "code_model": model_used,
        "files_changed": files_changed,
        "coder_notes": content[:2000],
        "action_id": action_id,
        "events": [
            {
                "type": "coder_completed",
                "files": files_changed,
                "model": model_used,
                "action_id": action_id,
            }
        ],
    }
